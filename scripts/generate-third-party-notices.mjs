import { readFile, readdir, writeFile, mkdir, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const lock = JSON.parse(await readFile(join(root, 'package-lock.json'), 'utf8'));
const packages = lock.packages ?? {};
const licenseNames = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

function packageName(location, metadata) {
  if (metadata.name) return metadata.name;
  const marker = 'node_modules/';
  const index = location.lastIndexOf(marker);
  return index < 0 ? location : location.slice(index + marker.length);
}

const runtime = Object.entries(packages)
  .filter(([location, metadata]) => location.includes('node_modules/') && metadata.dev !== true)
  .map(([location, metadata]) => ({
    location,
    name: packageName(location.replaceAll('\\', '/'), metadata),
    version: metadata.version,
    declaredLicense: metadata.license ?? 'See included license text',
  }))
  .sort((a, b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`));

const unique = new Map();
for (const item of runtime) unique.set(`${item.name}@${item.version}`, item);

const publicDir = join(root, 'public', 'licenses');
await rm(publicDir, { recursive: true, force: true });
await mkdir(publicDir, { recursive: true });

const sections = [];
for (const item of unique.values()) {
  const packageDir = join(root, item.location);
  const candidates = (await readdir(packageDir, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && licenseNames.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  if (candidates.length === 0) {
    throw new Error(`Runtime package ${item.name}@${item.version} has no bundled license file`);
  }
  const texts = [];
  for (const file of candidates) {
    texts.push((await readFile(join(packageDir, file), 'utf8')).trim());
  }
  sections.push(
    `## ${item.name} ${item.version}\n\nDeclared license: ${item.declaredLicense}\n\n${texts.join('\n\n---\n\n')}`,
  );
}

const preamble = `# Third-party notices

This file is generated by \`npm run licenses:generate\` from the exact runtime dependency graph in \`package-lock.json\`. Do not edit it manually. The packages below are redistributed in the production JavaScript bundle; their notices and license texts accompany the application.

waves-gui itself is licensed separately under the root MIT LICENSE.
`;
const markdown = `${preamble}\n${sections.join('\n\n')}\n`;
await writeFile(join(root, 'THIRD_PARTY_NOTICES.md'), markdown, 'utf8');
await writeFile(
  join(publicDir, 'THIRD_PARTY_NOTICES.txt'),
  markdown.replace(/^# /gm, '').replace(/^## /gm, '\n'),
  'utf8',
);
await writeFile(
  join(publicDir, 'README.txt'),
  'Runtime dependency notices and license texts. See THIRD_PARTY_NOTICES.txt.\n',
  'utf8',
);

console.log(`Generated notices for ${unique.size} runtime packages.`);
